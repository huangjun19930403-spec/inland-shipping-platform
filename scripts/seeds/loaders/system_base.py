def _expand_role_menu_parent_closure() -> None:
    parent_by_code = {item["menu_code"]: item.get("parent_code") for item in MENUS}
    ordered_codes = [item["menu_code"] for item in MENUS]

    for role_code, menu_codes in ROLE_MENU_CODES.items():
        expanded = set(menu_codes)
        for menu_code in list(menu_codes):
            parent_code = parent_by_code.get(menu_code)
            while parent_code:
                expanded.add(parent_code)
                parent_code = parent_by_code.get(parent_code)
        ROLE_MENU_CODES[role_code] = [code for code in ordered_codes if code in expanded]


_expand_role_menu_parent_closure()


def infer_menu_permission_code(item: dict) -> str | None:
    route_path = item.get("route_path")
    if not route_path:
        return item.get("permission_code")
    explicit = item.get("permission_code")
    if explicit:
        return explicit
    if route_path in {"/freight/wechat", "/freight/manual-create", "/freight/normalization"}:
        return "FREIGHT:WRITE"
    route_rules = (
        ("/system", "SYSTEM:READ"),
        ("/dictionary", "DICTIONARY:READ"),
        ("/address", "ADDRESS:READ"),
        ("/commodity", "COMMODITY:READ"),
        ("/vessels", "VESSEL:READ"),
        ("/freight", "FREIGHT:READ"),
        ("/route", "ROUTE:READ"),
        ("/analysis", "ANALYSIS:READ"),
        ("/tasks", "ANALYSIS:READ"),
        ("/audit", "AUDIT:READ"),
    )
    for prefix, permission_code in route_rules:
        if route_path == prefix or route_path.startswith(f"{prefix}/"):
            return permission_code
    return None


