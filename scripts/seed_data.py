async def seed_transport_nodes(db, waterway_map: dict, type_map: dict) -> None:
    """初始化运输节点（幂等）"""
    from sqlalchemy import select
    from app.models.address import TransportNode

    count = 0
    for (code, name, node_type_code, ww_code, province, city,
         lng, lat, node_level, berth_count, max_tonnage, annual_throughput) in TRANSPORT_NODES:
        res = await db.execute(select(TransportNode).where(TransportNode.code == code))
        if res.scalar_one_or_none():
            continue
        nt = type_map.get(node_type_code)
        ww = waterway_map.get(ww_code) if ww_code else None
        node = TransportNode(
            code=code, name=name,
            node_type_id=nt.id if nt else None,
            waterway_id=ww.id if ww else None,
            province=province, city=city,
            longitude=lng, latitude=lat,
            node_level=node_level,
            berth_count=berth_count,
            max_tonnage=max_tonnage,
            annual_throughput=str(annual_throughput),
            node_category=4, status=1, audit_status=1, sort_order=0,
        )
        db.add(node)
        count += 1
        if count % 50 == 0:
            await db.flush()
