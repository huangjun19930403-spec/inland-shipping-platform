async def seed_cargo_test_data(db) -> None:
    """写入货源测试记录（幂等）"""
    from sqlalchemy import select
    from app.models.cargo import CargoFreight, CommodityStandard

    # Build commodity code map
    res = await db.execute(select(CommodityStandard))
    std_map = {s.code: s.id for s in res.scalars().all()}

    today = date.today()
    count = 0
    for i, (origin_code, dest_code, commodity_code, tonnage, freight_price,
            price_type, contact_person, contact_phone) in enumerate(FREIGHT_TEMPLATES):
        freight_date = today - timedelta(days=(i % 7))
        freight_no = f"CS-{freight_date.strftime('%Y%m%d')}-SEED{i+1:04d}"
        res = await db.execute(select(CargoFreight).where(CargoFreight.freight_no == freight_no))
        if res.scalar_one_or_none():
            continue

        origin_name = CITIES_FOR_FREIGHT.get(origin_code, origin_code)
        dest_name = CITIES_FOR_FREIGHT.get(dest_code, dest_code)
        commodity_id = std_map.get(commodity_code)

        freight = CargoFreight(
            freight_no=freight_no, source_type="MANUAL", status="CONFIRMED",
            origin_admin_code=origin_code, origin_admin_name=origin_name,
            origin_raw_text=f"{origin_name}码头", origin_precision="CITY",
            dest_admin_code=dest_code, dest_admin_name=dest_name,
            dest_raw_text=f"{dest_name}码头", dest_precision="CITY",
            commodity_id=commodity_id, commodity_text=commodity_code,
            tonnage=tonnage, loading_date=freight_date,
            expire_date=freight_date + timedelta(days=7),
            freight_price=freight_price, price_type=price_type,
            price_unit="元/吨" if price_type == 1 else "元/单",
            contact_person=contact_person, contact_phone=contact_phone,
            collector_id=2, submitter_id=2,
            audit_status=1, auditor_id=1,
        )
        db.add(freight)
        count += 1
    await db.flush()
    logger.info(f"[seed] cargo_freights: {count}")


